create table public.recipe_extractions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  recipe_document_import_id uuid not null references public.recipe_document_imports (id) on delete restrict,
  source_type text not null check (source_type in ('image', 'pdf')),
  idempotency_key uuid not null,
  status text not null default 'queued' check (status in ('queued', 'processing', 'completed', 'failed', 'cancelled')),
  provider text not null,
  model text not null,
  recipe_data jsonb,
  failure_code text,
  failure_message text,
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, idempotency_key)
);

create index recipe_extractions_user_created_at_index
  on public.recipe_extractions (user_id, created_at desc);

alter table public.recipe_extractions enable row level security;

create table public.credit_ledgers (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  recipe_extraction_id uuid references public.recipe_extractions (id) on delete restrict,
  credits_delta integer not null,
  reason text not null,
  period_starts_at date not null,
  created_at timestamptz not null default now(),
  constraint credit_ledgers_successful_import_debit check (
    reason <> 'successful_recipe_import' or credits_delta = -1
  )
);

create unique index credit_ledgers_one_successful_import_per_extraction_index
  on public.credit_ledgers (recipe_extraction_id)
  where reason = 'successful_recipe_import';

create index credit_ledgers_user_period_index
  on public.credit_ledgers (user_id, period_starts_at)
  where reason = 'successful_recipe_import';

alter table public.credit_ledgers enable row level security;

create table public.jobs (
  id bigint generated by default as identity primary key,
  queue varchar(255) not null,
  payload text not null,
  attempts smallint not null,
  reserved_at integer,
  available_at integer not null,
  created_at integer not null
);

create index jobs_queue_index on public.jobs (queue);

alter table public.jobs enable row level security;

create table public.failed_jobs (
  id uuid primary key default gen_random_uuid(),
  uuid varchar(255) not null unique,
  connection text not null,
  queue text not null,
  payload text not null,
  exception text not null,
  failed_at timestamptz not null default now()
);

alter table public.failed_jobs enable row level security;
